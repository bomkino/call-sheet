"""Copies the Call Sheet logo paths out of the brand files into src/explainer/logoPaths.ts.

    python3 scripts/extract_logo.py [path/to/brand]     default: the repo's brand/ (../../brand)

The letters, the loop and the pen's centre line come from brand/web/logo.svg;
the line under the logo comes from brand/logo/call-sheet-logo-tagline.svg. Both
are drawn by brand/tools/make_brand.py in the same coordinates.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
brand = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent.parent / "brand"
web = (brand / "web/logo.svg").read_text()
tag = (brand / "logo/call-sheet-logo-tagline.svg").read_text()
paths = re.findall(r'<path[^>]*\sd="([^"]+)"', web)
pen, letters, loop = paths[0], paths[1], paths[2]
tpaths = re.findall(r'<path[^>]*\sd="([^"]+)"', tag)
assert tpaths[0] == letters, "tagline lockup letters differ from the web logo"
line = tpaths[2]
vb_web = re.search(r'viewBox="([^"]+)"', web).group(1)
vb_tag = re.search(r'viewBox="([^"]+)"', tag).group(1)
title = re.search(r"<title>([^<]+)</title>", tag).group(1)
out = ROOT / "src/explainer/logoPaths.ts"
out.write_text(
    "// Generated by scripts/extract_logo.py from the Call Sheet brand files. Don't edit by hand.\n"
    f"export const LOGO_VIEWBOX = {json.dumps(vb_web)};\n"
    f"export const LOCKUP_VIEWBOX = {json.dumps(vb_tag)};\n"
    f"export const LOCKUP_TITLE = {json.dumps(title)};\n"
    f"export const LETTERS = {json.dumps(letters)};\n"
    f"export const LOOP = {json.dumps(loop)};\n"
    f"export const PEN = {json.dumps(pen)};\n"
    f"export const LINE = {json.dumps(line)};\n"
)
print("wrote", out, "| lockup:", title, "| viewBoxes", vb_web, "/", vb_tag)
